// Evidence. Writes eval/results.md with real numbers, even when they are weak (spec Phase 5).
// For each player with enough data, holds out one of their matches, builds their clone from the rest, and
// on the held-out match compares three policies: the player's own clone, the basic bot, and a clone of a
// different player. Then position error, handoff rate, and a transfer test.
//
// Run with: npm run eval
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { MatchFile, Policy, Slot } from '@rewind/engine';
import { BasicBot, buildClone, loadMatches, matchesOf, playerNames, slotOf } from '@rewind/clone';
import { cloneAccuracy, handoffRate, positionError } from './metrics';
import { transferCase } from './transfer';

const OUT = fileURLToPath(new URL('./results.md', import.meta.url));
const pct = (v: number) => `${(v * 100).toFixed(0)}%`;

type Row = { player: string; policy: string; bothAcc: number; moveAcc: number; fireAcc: number; posErr: number; decisions: number };

function main(): void {
  const all = loadMatches();
  const names = playerNames(all);
  const lines: string[] = [];
  const started = new Date().toISOString();

  lines.push('# Rewind — evidence');
  lines.push('');
  lines.push(`Generated by \`npm run eval\` on ${started}. All numbers are measured on held-out matches the clone never trained on. Weak numbers are reported as-is.`);
  lines.push('');
  lines.push(`Dataset: ${all.length} recorded matches, ${names.length} distinct players.`);
  lines.push('');

  // Players with at least two matches can have one held out; others we note and skip for accuracy.
  const evaluable = names.filter((n) => matchesOf(all, n).length >= 2);
  const singletons = names.filter((n) => matchesOf(all, n).length === 1);

  // Pick a distinct "other player" with enough data, for the cross-clone baseline.
  const otherPool = evaluable.length >= 2 ? evaluable : names.filter((n) => matchesOf(all, n).length >= 1);

  const accRows: Row[] = [];
  const handoffLines: string[] = [];
  const transferLines: string[] = [];

  for (const player of evaluable) {
    const mine = matchesOf(all, player);
    const held = mine[0]; // hold out the first match
    const slot = slotOf(held, player) as Slot;

    // Three policies.
    const own = buildClone(player, { allMatches: all, holdOut: [held.id] });
    const bot: Policy = new BasicBot();
    const otherName = otherPool.find((n) => n !== player) ?? player;
    const other = buildClone(otherName, { allMatches: all, holdOut: matchesOf(all, otherName).length > 1 ? [held.id] : [] });

    const policies: { name: string; policy: Policy }[] = [
      { name: `${player} clone (own)`, policy: own.guarded },
      { name: 'basic bot', policy: bot },
      { name: `${otherName} clone (other)`, policy: other.guarded },
    ];

    for (const { name, policy } of policies) {
      const acc = cloneAccuracy(held, slot, policy);
      const pos = positionError(held, slot, policy);
      accRows.push({
        player, policy: name,
        bothAcc: acc.bothMatch / Math.max(1, acc.decisions),
        moveAcc: acc.moveMatch / Math.max(1, acc.decisions),
        fireAcc: acc.fireMatch / Math.max(1, acc.decisions),
        posErr: pos.avgError,
        decisions: acc.decisions,
      });
    }

    // Handoff rate: the own clone's breaker on the held-out match.
    const h = handoffRate(held, slot, own.guarded);
    handoffLines.push(`- **${player}** on held-out \`${held.id}\`: breaker fired on ${pct(h.rate)} of ${h.ticks} decision ticks (limit ${own.breakerLimit.toFixed(2)}).`);

    // Transfer test.
    const tc = transferCase(held, player, all);
    if (tc) {
      const wins = tc.retries.filter((r) => r.playerWon).length;
      transferLines.push(
        `- **${player}**, round ${tc.round} of \`${tc.matchId}\` (lost), fork tick ${tc.forkTick}:\n` +
        `  - first attempt: lost (recorded)\n` +
        `  - retries (own clone vs opponent clone): won ${wins} of ${tc.retries.length}\n` +
        `  - fresh attempt (best plan): ${tc.freshAttempt ? `"${tc.freshAttempt.plan}" — win ${pct(tc.freshAttempt.winRate)}, survive ${pct(tc.freshAttempt.survivalRate)}` : 'none'}`,
      );
    }
  }

  // --- Clone accuracy table ---------------------------------------------------------------------
  lines.push('## 1. Clone accuracy (held-out)');
  lines.push('');
  lines.push('Share of decisions where the policy matched the real person. "Both" = move direction and fire choice both match (the spec\'s measure); move and fire shown separately too.');
  lines.push('');
  lines.push('| Player | Policy | Both | Move | Fire | Decisions |');
  lines.push('| --- | --- | ---: | ---: | ---: | ---: |');
  for (const r of accRows) {
    lines.push(`| ${r.player} | ${r.policy} | ${pct(r.bothAcc)} | ${pct(r.moveAcc)} | ${pct(r.fireAcc)} | ${r.decisions} |`);
  }
  lines.push('');

  // --- Position error ---------------------------------------------------------------------------
  lines.push('## 2. Position error (1 second, held-out)');
  lines.push('');
  lines.push('From each held-out decision moment, the policy runs for 1 second (opponent frozen) and we measure the distance in map units to where the real person actually ended. Lower is more like them.');
  lines.push('');
  lines.push('| Player | Policy | Avg error (units) |');
  lines.push('| --- | --- | ---: |');
  for (const r of accRows) lines.push(`| ${r.player} | ${r.policy} | ${r.posErr.toFixed(2)} |`);
  lines.push('');

  // --- Handoff rate -----------------------------------------------------------------------------
  lines.push('## 3. Handoff rate (circuit breaker)');
  lines.push('');
  lines.push('Share of decision ticks on the held-out match where the clone was too far from anything it had seen, so the breaker handed control to the basic bot.');
  lines.push('');
  lines.push(...(handoffLines.length ? handoffLines : ['- (no evaluable players)']));
  lines.push('');

  // --- Transfer test ----------------------------------------------------------------------------
  lines.push('## 4. Transfer test');
  lines.push('');
  lines.push('For a round each player lost: their first (recorded) attempt, retries by their own clone against the opponent clone, and the best what-if plan from the same fork.');
  lines.push('');
  lines.push(...(transferLines.length ? transferLines : ['- (no lost rounds found for evaluable players)']));
  lines.push('');

  // --- Notes ------------------------------------------------------------------------------------
  lines.push('## Notes and limits');
  lines.push('');
  lines.push(`- Players with only one recorded match (no hold-out possible): ${singletons.length ? singletons.map((n) => `\`${n}\``).join(', ') : 'none'}. They are excluded from the accuracy and transfer tables.`);
  lines.push('- The dataset is small, so treat these as a demo of the method, not a benchmark. The point is that the own clone should match the person more often, land closer in position, and break less than a clone of someone else.');
  lines.push('');

  writeFileSync(OUT, lines.join('\n'));
  console.log(`wrote ${OUT}`);
  console.log(`players evaluated: ${evaluable.length}, singletons: ${singletons.length}`);
}

main();
